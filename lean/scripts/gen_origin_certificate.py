"""Propose the polynomial certificate at the origin and emit it as Lean data.

Untrusted: the coefficients are the power series of the regular solution in
r = s^(3/2) and of its derivatives with respect to the two parameters,
evaluated with high-precision floats and rounded. What is accepted is what
`origin_checks.origin_summarize` decides, mirrored by the Lean kernel in
Calabi/Origin/Cert.lean.

Usage: python3 scripts/gen_origin_certificate.py [--degree N]
"""
from pathlib import Path
import argparse
import json
import gmpy2
from gmpy2 import mpfr, mpz
import origin_checks as oc
from shot_checks import SCALE_P, SCALE_U

ROOT = Path(__file__).resolve().parents[1]
HEADER = "/-! Generated by scripts/gen_origin_certificate.py. Do not edit. -/"


def nearest(x):
    return int(mpz(gmpy2.floor(x + mpfr("0.5"))))


def series(k, d, n):
    """Coefficients a_i of p = sum a_i r^i, with their derivatives in k and d."""
    z = [[1 + d, mpfr(0), mpfr(1)], [k, mpfr(1), mpfr(0)]]
    b = []
    for i in range(n - 1):
        f = 1 / z[0][0]
        first = f if i == 0 else -f * sum(z[t][0] * b[i - t][0] for t in range(1, i + 1))
        q = [first]
        for j in (1, 2):
            acc = sum(z[t][j] * (first if t == 0 else b[i - t][0]) for t in range(i + 1))
            acc += sum(z[t][0] * b[i - t][j] for t in range(1, i + 1))
            q.append(-f * acc)
        b.append(q)
        den = mpfr(27 * (i + 1) * (i + 8) * (i + 9))
        z.append([8 * (q[j] - (1 if (i == 0 and j == 0) else 0)) / den for j in range(3)])
    z[0][0] -= 1
    return z


def ints(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def tup(values):
    return "⟨" + ", ".join(str(v) for v in values) + "⟩"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--degree", type=int, default=60)
    args = parser.parse_args()
    gmpy2.get_context().precision = 900
    blocks = json.loads((ROOT / "certificate/shot_blocks.json").read_text())
    centre = json.loads((ROOT / "certificate/shot_centre.json").read_text())
    dnum = int(blocks["meta"]["dnum"])
    M = [[int(x) for x in row] for row in blocks["meta"]["preconditioner_over_scaleU"]]
    kz, dz = M[0], M[1]
    knum = nearest(mpfr(centre["k"]) * SCALE_P)
    n = args.degree
    z = series(mpfr(knum) / SCALE_P, mpfr(dnum) / SCALE_P, n)
    q0 = [nearest(z[i][0] * oc.SCALE_O) for i in range(n + 1)]
    q0[0] = dnum * (oc.SCALE_O // SCALE_P)
    q0[1] = knum * (oc.SCALE_O // SCALE_P)
    tangents = []
    for m in range(2):
        q = [nearest((z[i][1] * kz[m] + z[i][2] * dz[m]) / SCALE_U * oc.SCALE_T)
             for i in range(n + 1)]
        q[0] = dz[m] * (oc.SCALE_T // 2 ** 64)
        q[1] = kz[m] * (oc.SCALE_T // 2 ** 64)
        tangents.append(q)
    s = oc.origin_summarize(dnum, knum, dz, kz, q0, tangents[0], tangents[1])
    assert s is not None, "origin rejected"
    text = (
        "import Calabi.Origin.Cert\nimport Calabi.Shot.Data.Params\n\n"
        f"{HEADER}\n\nnamespace Calabi.Origin.Data\n\nopen Calabi.Shot Calabi.Shot.Data\n\n"
        "/-- The centre value of the parameter `k`, as an integer over `scaleP`. -/\n"
        f"def knum : Int := {knum}\n\n"
        "/-- `k = (knum / scaleP) + (kz1 z₁ + kz2 z₂) / scaleU` on the parameter box. -/\n"
        f"def kz1 : Int := {kz[0]}\n\ndef kz2 : Int := {kz[1]}\n\n"
        "/-- The regular solution at the centre is close to `q0(r) / 2^192`. -/\n"
        f"def q0 : Poly :=\n  {ints(q0)}\n\n"
        "/-- Its derivatives in `z₁`, `z₂` are close to `q1(r) / 2^128`, `q2(r) / 2^128`. -/\n"
        f"def q1 : Poly :=\n  {ints(tangents[0])}\n\n"
        f"def q2 : Poly :=\n  {ints(tangents[1])}\n\n"
        "def originSum : OriginSummary :=\n"
        f"  {{ e0 := {s['e0']},\n    e1 := {s['e1']},\n    n0 := {s['n0']},\n"
        f"    nQ := {s['nQ']},\n    nL := {s['nL']},\n"
        f"    j0 := {tup(s['j0'])},\n    j1 := {tup(s['j1'])},\n    j2 := {tup(s['j2'])} }}\n\n"
        "/-- The kernel recomputes the digest of the certificate at the origin. -/\n"
        "theorem origin_ok :\n"
        "    originSummarize dnum knum dz1 kz1 dz2 kz2 q0 q1 q2 = some originSum := by\n"
        "  decide +kernel\n\nend Calabi.Origin.Data\n")
    path = ROOT / "Calabi/Origin/Data.lean"
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
    (ROOT / "certificate/origin.json").write_text(json.dumps(
        dict(degree=n, knum=str(knum), kz=[str(x) for x in kz],
             q0=[str(c) for c in q0], q1=[str(c) for c in tangents[0]],
             q2=[str(c) for c in tangents[1]],
             summary={key: ([str(x) for x in v] if isinstance(v, list) else str(v))
                      for key, v in s.items()})) + "\n")
    print(f"degree {n}, e0 / 2^384 = {s['e0'] / 2.0 ** 384:.3e}, "
          f"e1 / 2^320 = {s['e1'] / 2.0 ** 320:.3e}, n0 / 2^192 = {s['n0'] / 2.0 ** 192:.4f}")


if __name__ == "__main__":
    main()
