"""Propose the certificate for the finite shot and emit it as Lean data.

Untrusted: high-precision numerics choose the polynomials, the frames and the
linear responses. What is accepted is exactly what the exact integer
computations decide: `shot_checks.summarize` for each block and
`shot_lohner.run` for the chain, mirrored by the Lean kernel in
Calabi/Shot/Core.lean and Calabi/Shot/Chain.lean.

Usage: python3 scripts/gen_shot_certificate.py [--chunk M]
"""
from pathlib import Path
import argparse
import json
import time
import gmpy2
from gmpy2 import mpfr, mpz
import shot_numerics as num
import shot_checks as chk
import shot_lohner as lo

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "Calabi/Shot/Data"
N_LEFT, N_CENTRE = 48, 40
FRAME_BITS = 12
HEADER = "/-! Generated by scripts/gen_shot_certificate.py. Do not edit. -/"


def nearest(x):
    return int(mpz(gmpy2.floor(x + mpfr("0.5"))))


def fit(coeffs, start, scale, n):
    """Integer coefficients of degree n: rounded Taylor coefficients above
    degree two, and the three lowest fixed by the exact jet at t = -1."""
    c = [0, 0, 0] + [nearest(coeffs[i] * scale) for i in range(3, n + 1)]
    s2 = sum(i * (i - 1) * c[i] * (-1) ** i for i in range(3, n + 1))
    assert (start[2] - s2) % 2 == 0
    c[2] = (start[2] - s2) // 2
    c[1] = start[1] - sum(i * c[i] * (-1) ** (i - 1) for i in range(2, n + 1))
    c[0] = start[0] - sum(c[i] * (-1) ** i for i in range(1, n + 1))
    while len(c) > 3 and c[-1] == 0:
        c.pop()
    return c


def degree(coeffs, scale_bits):
    """Smallest degree whose discarded tail is below the rounding level."""
    tol = mpfr(2) ** (-(scale_bits + 2))
    n = len(coeffs) - 1
    tail = mpfr(0)
    while n > 3:
        tail += (n + 1) ** 3 * abs(coeffs[n])
        if tail >= tol:
            break
        n -= 1
    return min(n + 1, len(coeffs) - 1)


def blocks_and_summaries(k, dnum):
    d_hat = mpfr(dnum) / chk.SCALE_P
    jet, dk, dd = num.origin_jet(k, d_hat)
    layout = num.blocks()
    H0 = layout[0][0]
    start = [nearest(jet[0] * chk.SCALE_P), nearest(jet[1] / H0 * chk.SCALE_P),
             2 * nearest(jet[2] / H0 ** 2 * chk.SCALE_P / 2)]
    unit = [[chk.SCALE_U, 0, 0], [0, chk.SCALE_U, 0], [0, 0, chk.SCALE_U], [0, 0, 0]]
    blocks, summaries = [], []
    for index, (H, A) in enumerate(layout):
        sj = [mpfr(v) / chk.SCALE_P for v in start]
        z = num.block_series(H, A, d_hat, sj, N_LEFT, N_CENTRE)
        col = lambda c: [z[i][c] for i in range(len(z))]
        blk = dict(H=H, A=A, P=fit(col(0), start, chk.SCALE_P, degree(col(0), 128)))
        for c, name in enumerate(("U0", "U1", "U2", "Ud"), start=1):
            blk[name] = fit(col(c), unit[c - 1], chk.SCALE_U, degree(col(c), 64))
        summary = chk.summarize(dnum, blk)
        assert summary is not None, f"block {index} rejected"
        assert summary["start"] == start
        blocks.append(blk)
        summaries.append(summary)
        nxt = layout[index + 1][0] if index + 1 < len(layout) else H
        g = H // nxt
        start = [summary["stop"][0], summary["stop"][1] * g, summary["stop"][2] * g * g]
    return blocks, summaries, (dk, dd)


def chain(centre, summaries, origin_tangent):
    """Preconditioner, initial response, frames, responses and the fold."""
    dk, dd = origin_tangent
    M = [[nearest(mpfr(x) * chk.SCALE_U) for x in row] for row in centre["inverse_jacobian"]]
    dz = M[1]
    H0 = summaries[0]["H"]
    L0 = [[nearest((dk[a] * M[0][c] + dd[a] * M[1][c]) / H0 ** a) for c in range(2)]
          for a in range(3)]
    frames, Ls = lo.propose(summaries, L0, dz, frame_bits=FRAME_BITS)
    history, where = lo.run(summaries, frames, Ls, dz)
    assert history is not None, f"chain rejected at block {where}"
    return M, dz, frames, Ls, history


def write(path, text):
    """Leave an unchanged file alone, so that its checked artifact stays current."""
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def lean_list(values, indent="    ", width=6):
    rows = [", ".join(values[i:i + width]) for i in range(0, len(values), width)]
    return "[" + (",\n" + indent).join(rows) + "]"


def ints(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def tup(values):
    return "⟨" + ", ".join(str(v) for v in values) + "⟩"


def emit_blocks(dnum, dz, blocks, summaries, chunk):
    DATA.mkdir(parents=True, exist_ok=True)
    write(DATA / "Params.lean", 
        f"import Calabi.Shot.Certified\n\n{HEADER}\n\nnamespace Calabi.Shot.Data\n\n"
        "/-- The centre value of the parameter `d`, as an integer over `scaleP`. -/\n"
        f"def dnum : Int := {dnum}\n\n"
        "/-- `d = (dnum / scaleP) + (dz1 z₁ + dz2 z₂) / scaleU` on the parameter box. -/\n"
        f"def dz1 : Int := {dz[0]}\n\ndef dz2 : Int := {dz[1]}\n\nend Calabi.Shot.Data\n")
    names = []
    for first in range(0, len(blocks), chunk):
        name = f"Blocks{first // chunk:02d}"
        names.append(name)
        last = min(first + chunk, len(blocks))
        lines = ["import Calabi.Shot.Data.Params", "", HEADER, "", "namespace Calabi.Shot.Data", ""]
        for index in range(first, last):
            b, s = blocks[index], summaries[index]
            lines += [
                f"def blk{index} : Block :=",
                f"  {{ H := {b['H']}, A := {b['A']},",
                f"    P := {ints(b['P'])},",
                f"    U0 := {ints(b['U0'])},",
                f"    U1 := {ints(b['U1'])},",
                f"    U2 := {ints(b['U2'])},",
                f"    Ud := {ints(b['Ud'])} }}", "",
                f"def sum{index} : Summary :=",
                f"  {{ H := {s['H']}, A := {s['A']},",
                f"    start := {tup(s['start'])}, stop := {tup(s['stop'])},",
                f"    t0 := {tup(s['T'][0])}, t1 := {tup(s['T'][1])},",
                f"    t2 := {tup(s['T'][2])}, td := {tup(s['T'][3])},",
                f"    eps := {s['epsP']} }}", "",
                f"theorem ok{index} : summarize dnum blk{index} = some sum{index} := by",
                "  decide +kernel", ""]
        pairs = [f"(blk{i}, sum{i})" for i in range(first, last)]
        proof = "certified_nil dnum"
        for i in reversed(range(first, last)):
            proof = f"certified_cons ok{i} ({proof})"
        lines += [
            "/-- The blocks of this file with their summaries. -/",
            f"def chunk{first // chunk:02d} : List (Block × Summary) :=",
            f"  {lean_list(pairs)}", "",
            f"theorem chunk{first // chunk:02d}_ok : ∀ p ∈ chunk{first // chunk:02d}, Certified dnum p :=",
            f"  {proof}", "", "end Calabi.Shot.Data"]
        write(DATA / f"{name}.lean", "\n".join(lines) + "\n")
    count = len(names)
    chunks = [f"chunk{i:02d}" for i in range(count)]
    nested = chunks[-1]
    append_proof = f"{chunks[-1]}_ok"
    for c in reversed(chunks[:-1]):
        nested = f"{c} ++ ({nested})"
        append_proof = f"certified_append {c}_ok ({append_proof})"
    for old in DATA.glob("Blocks*.lean"):
        if old.stem not in names:
            old.unlink()
    write(DATA / "All.lean", 
        "".join(f"import Calabi.Shot.Data.{n}\n" for n in names)
        + f"\n{HEADER}\n\nnamespace Calabi.Shot.Data\n\n"
        "/-- All blocks of the finite shot, in order, with their summaries. -/\n"
        f"def pairs : List (Block × Summary) :=\n  {nested}\n\n"
        "/-- Every block of the finite shot has a kernel-checked summary. -/\n"
        "theorem pairs_ok : ∀ p ∈ pairs, Certified dnum p :=\n"
        f"  {append_proof}\n\n"
        "end Calabi.Shot.Data\n")
    return names


def emit_chain(frames, Ls, rho_end, radius, count):
    flat = lambda m: tup([x for row in m for x in row])
    write(DATA / "ChainData.lean",
        "import Calabi.Shot.Chain\nimport Calabi.Shot.Data.All\n\n"
        f"{HEADER}\n\nset_option maxRecDepth 100000\n\nnamespace Calabi.Shot.Data\n\n"
        "/-- Integer frames at the block boundaries (proposed, checked by `chain_ok`). -/\n"
        f"def frame0 : Mat3 := {flat(frames[0])}\n\n"
        f"def framesTail : List Mat3 :=\n  {lean_list([flat(f) for f in frames[1:]], width=2)}\n\n"
        "def frames : List Mat3 := frame0 :: framesTail\n\n"
        "/-- The frame at `s = 56`. -/\n"
        f"def frameEnd : Mat3 := {flat(frames[-1])}\n\n"
        "/-- The linear response at `s = 1` to the two parameters, over `scaleU`. -/\n"
        f"def resp0 : Mat32 := {flat(Ls[0])}\n\n"
        f"def responsesTail : List Mat32 :=\n  {lean_list([flat(l) for l in Ls[1:]], width=2)}\n\n"
        "/-- Linear responses to the two parameters, over `scaleU`. -/\n"
        "def responses : List Mat32 := resp0 :: responsesTail\n\n"
        "/-- The linear response at `s = 56`. -/\n"
        f"def respEnd : Mat32 := {flat(Ls[-1])}\n\n"
        "def sums : List Summary := pairs.map Prod.snd\n\n"
        "/-- The remainder bound at `s = 56`, in the last frame. -/\n"
        f"def rhoEnd : Nat3 := {tup(rho_end)}\n\n"
        "/-- The kernel runs the whole chain. -/\n"
        "theorem chain_ok :\n"
        "    chainRun dz1 dz2 sums frames responses (initial frame0) = some rhoEnd := by\n"
        "  decide +kernel\n\n"
        "theorem chain_start :\n"
        "    chainStart sums frames responses = some (sum0, frame0, resp0) := by\n"
        "  decide +kernel\n\n"
        "theorem chain_end :\n"
        f"    chainEnd sums frames responses = some (sum{count - 1}, frameEnd, respEnd) := by\n"
        "  decide +kernel\n\n"
        "/-- Every block lies in `1 ≤ s ≤ 56`. -/\n"
        "theorem sums_range : sums.all (inRange 1 56) = true := by\n"
        "  decide +kernel\n\n"
        "/-- Componentwise bound for the remainder at `s = 56`, over `scaleE`. -/\n"
        f"def radEnd : Nat3 := {tup(radius)}\n\n"
        "theorem radius_end : radius frameEnd rhoEnd = radEnd := by\n"
        "  decide +kernel\n\n"
        "theorem frameEnd_det_pos : 0 < frameEnd.det := by\n"
        "  decide +kernel\n\nend Calabi.Shot.Data\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--chunk", type=int, default=32)
    args = parser.parse_args()
    begin = time.time()
    centre = json.loads((ROOT / "certificate/shot_centre.json").read_text())
    k = mpfr(centre["k"])
    dnum = nearest(mpfr(centre["d"]) * chk.SCALE_P)
    blocks, summaries, origin_tangent = blocks_and_summaries(k, dnum)
    M, dz, frames, Ls, history = chain(centre, summaries, origin_tangent)
    assert all(lo.in_range(1, 56, s) for s in summaries)
    assert summaries[0]["A"] - 1 == summaries[0]["H"]
    assert summaries[-1]["A"] + 1 == 56 * summaries[-1]["H"]
    names = emit_blocks(dnum, dz, blocks, summaries, args.chunk)
    radius = lo.final_radius(frames[-1], history[-1])
    emit_chain(frames, Ls, history[-1], radius, len(blocks))
    Hn = summaries[-1]["H"]
    R = 2.0 ** (-lo.R_EXP)
    meta = dict(dnum=str(dnum), blocks=len(blocks), files=names, frame_bits=FRAME_BITS,
                box_exponent=lo.R_EXP, initial_tolerance_exponent=lo.MU_EXP,
                preconditioner_over_scaleU=[[str(x) for x in row] for row in M],
                degree_P=[len(b["P"]) - 1 for b in blocks],
                eps_over_scaleE=[str(s["epsP"]) for s in summaries],
                end_jet_over_scaleP=[str(x) for x in summaries[-1]["stop"]],
                end_response_over_scaleU=[[str(x) for x in row] for row in Ls[-1]],
                end_radius_over_scaleE=[str(x) for x in radius],
                seconds=round(time.time() - begin, 1))
    dest = ROOT / "certificate"
    dest.mkdir(exist_ok=True)
    (dest / "shot_blocks.json").write_text(json.dumps(
        dict(meta=meta,
             blocks=[{key: (v if isinstance(v, int) else [str(x) for x in v])
                      for key, v in b.items()} for b in blocks],
             summaries=[dict(H=s["H"], A=s["A"], start=[str(x) for x in s["start"]],
                             stop=[str(x) for x in s["stop"]],
                             T=[[str(x) for x in j] for j in s["T"]], eps=str(s["epsP"]))
                        for s in summaries],
             frames=frames, responses=[[[str(x) for x in row] for row in l] for l in Ls],
             rho=[[str(x) for x in r] for r in history])) + "\n")
    eps = [s["epsP"] / chk.SCALE_E for s in summaries]
    print(f"blocks {len(blocks)}, degree P max {max(meta['degree_P'])}, eps max {max(eps):.3e}")
    print("end radius / R (physical jet):",
          ["%.3e" % (radius[a] / chk.SCALE_E * Hn ** a / R) for a in range(3)])
    print(f"files: {len(names)} block files, All.lean, ChainData.lean; {meta['seconds']} s")


if __name__ == "__main__":
    main()
