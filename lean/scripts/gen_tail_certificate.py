"""Propose the approximate tail on [56, oo) and emit it as Lean data.

Untrusted: the coefficients are the formal expansion of the profile at
infinity, evaluated at the centre parameter and rounded. What is accepted is
what `tail_checks.tail_summarize` decides, mirrored by the Lean kernel in
Calabi/Tail/Cert.lean.

Usage: python3 scripts/gen_tail_certificate.py [--order J]
"""
from fractions import Fraction as F
from pathlib import Path
import argparse
import json
import shot_tail_numerics as tn
import tail_checks as tc
from shot_checks import SCALE_P, SCALE_E

ROOT = Path(__file__).resolve().parents[1]
HEADER = "/-! Generated by scripts/gen_tail_certificate.py. Do not edit. -/"


def tail_poly(dnum, order):
    """Integer coefficients of P with a(s) = P((56/s)^3) / 2^128."""
    d_hat = F(dnum, SCALE_P)
    coeffs = tn.formal_tail(order)
    P = [0]
    for j in range(1, order + 1):
        value = sum(c * d_hat ** i for i, c in enumerate(coeffs[j]))
        P.append(round(value * SCALE_P / F(56) ** (3 * j)))
    return P


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--order", type=int, default=10)
    args = parser.parse_args()
    blocks = json.loads((ROOT / "certificate/shot_blocks.json").read_text())
    dnum = int(blocks["meta"]["dnum"])
    P = tail_poly(dnum, args.order)
    summary = tc.tail_summarize(dnum, P)
    assert summary is not None, "tail rejected"
    text = (
        "import Calabi.Tail.Cert\nimport Calabi.Shot.Data.Params\n\n"
        f"{HEADER}\n\nnamespace Calabi.Tail.Data\n\nopen Calabi.Shot Calabi.Shot.Data\n\n"
        "/-- The approximate tail is `tailP((56/s)³) / 2^128`. -/\n"
        f"def tailP : Poly :=\n  [{', '.join(str(c) for c in P)}]\n\n"
        "def tailSum : TailSummary :=\n"
        f"  {{ v := {summary['v']}, d1 := {summary['d1']}, d2 := {summary['d2']},\n"
        f"    l1 := {summary['l1']}, eps := {summary['eps']} }}\n\n"
        "/-- The kernel recomputes the digest of the approximate tail. -/\n"
        "theorem tail_ok : tailSummarize dnum tailP = some tailSum := by\n"
        "  decide +kernel\n\nend Calabi.Tail.Data\n")
    path = ROOT / "Calabi/Tail/Data.lean"
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
    (ROOT / "certificate/tail.json").write_text(json.dumps(
        dict(order=args.order, P=[str(c) for c in P],
             summary={k: str(v) for k, v in summary.items()})) + "\n")
    print(f"order {args.order}, eps {summary['eps'] / SCALE_E:.3e}, "
          f"|a| <= {summary['l1'] / SCALE_P:.3e}")


if __name__ == "__main__":
    main()
